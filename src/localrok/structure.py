"""Stage 5: per-document structure-quality report."""

from __future__ import annotations

import sqlite3
from collections import Counter
from pathlib import Path

from localrok import __version__


def clamp01(x: float) -> float:
    return max(0.0, min(1.0, x))


def structure_score(
    heading_count: int,
    page_count: int | None,
    orphan_char_ratio: float,
    max_depth: int,
    duplicate_char_ratio: float = 0.0,
) -> float:
    """Score navigability.

    `heading_count` must exclude duplicated paths: repeated page furniture
    misread as headings would otherwise inflate the count, so the score would
    rise with the very defect it is meant to detect. `duplicate_char_ratio`
    penalises directly, because text under a duplicated path is unaddressable
    by `docs_read` and unidentifiable in a citation.
    """
    pages = max(1, page_count or 1)
    return clamp01(
        0.40 * clamp01(heading_count / max(1, pages * 0.5))
        + 0.30 * (1.0 - orphan_char_ratio)
        + 0.30 * clamp01((max_depth - 1) / 2.0)
    ) * (1.0 - clamp01(duplicate_char_ratio))


def compute_document_signals(conn: sqlite3.Connection, doc_id: int) -> dict:
    doc = conn.execute("SELECT * FROM documents WHERE doc_id = ?", (doc_id,)).fetchone()
    sections = conn.execute(
        "SELECT * FROM sections WHERE doc_id = ? ORDER BY ordinal", (doc_id,)
    ).fetchall()
    page_count = doc["page_count"] or 0
    max_depth = max((s["depth"] for s in sections), default=0)
    depth_1_count = sum(1 for s in sections if s["depth"] == 1)
    total_chars = sum(s["char_count"] for s in sections) or 1
    orphan_chars = sum(s["char_count"] for s in sections if s["depth"] == 0)
    orphan_char_ratio = orphan_chars / total_chars

    path_counts: Counter[str] = Counter(s["section_path"] for s in sections if s["depth"] >= 1)
    duplicate_paths = {p for p, n in path_counts.items() if n > 1}
    duplicate_chars = sum(
        s["char_count"] for s in sections if s["section_path"] in duplicate_paths
    )
    duplicate_char_ratio = duplicate_chars / total_chars
    worst_duplicate = None
    if duplicate_paths:
        worst = max(duplicate_paths, key=lambda p: path_counts[p])
        worst_duplicate = f"{worst!r} ×{path_counts[worst]}"
    # Distinct addressable headings, not raw heading rows.
    heading_count = len(path_counts)
    headed = [s["char_count"] for s in sections if s["depth"] >= 1]
    mean_section_chars = (sum(headed) / len(headed)) if headed else 0.0

    pages_with_heading: set[int] = set()
    for s in sections:
        if s["depth"] >= 1 and s["page_start"] is not None:
            pages_with_heading.add(s["page_start"])
    pages_without_heading = 0
    if page_count:
        pages_without_heading = sum(
            1 for p in range(1, page_count + 1) if p not in pages_with_heading
        )

    score = structure_score(
        heading_count, page_count, orphan_char_ratio, max_depth, duplicate_char_ratio
    )
    conn.execute(
        "UPDATE documents SET structure_score = ? WHERE doc_id = ?",
        (score, doc_id),
    )
    return {
        "filename": doc["filename"],
        "page_count": page_count,
        "heading_count": heading_count,
        "max_depth": max_depth,
        "depth_1_count": depth_1_count,
        "orphan_char_ratio": orphan_char_ratio,
        "duplicate_path_count": len(duplicate_paths),
        "duplicate_char_ratio": duplicate_char_ratio,
        "worst_duplicate": worst_duplicate,
        "pages_without_heading": pages_without_heading,
        "mean_section_chars": mean_section_chars,
        "structure_score": score,
        "docling_version": doc["docling_version"],
    }


def write_structure_report(conn: sqlite3.Connection, dest: Path) -> str:
    docs = conn.execute("SELECT doc_id FROM documents ORDER BY filename").fetchall()
    rows = [compute_document_signals(conn, d["doc_id"]) for d in docs]
    conn.commit()

    lines = [
        f"# Structure report — {len(rows)} documents",
        f"Generated by LocalRök {__version__}",
        "",
        "Flag threshold: structure_score < 0.5 requires human review before "
        "trusting that document's corpus-map entry.",
        "",
    ]
    flagged = []
    for r in rows:
        mark = " ⚠" if r["structure_score"] < 0.5 else ""
        lines.append(f"## {r['filename']}{mark}")
        lines.append(f"- structure_score: {r['structure_score']:.2f}")
        lines.append(f"- heading_count: {r['heading_count']}")
        lines.append(f"- max_depth: {r['max_depth']}")
        lines.append(f"- depth_1_count: {r['depth_1_count']}")
        lines.append(f"- orphan_char_ratio: {r['orphan_char_ratio']:.2f}")
        lines.append(f"- duplicate_path_count: {r['duplicate_path_count']}")
        lines.append(f"- duplicate_char_ratio: {r['duplicate_char_ratio']:.2f}")
        if r["worst_duplicate"]:
            lines.append(f"- worst duplicate path: {r['worst_duplicate']}")
            lines.append(
                "  → text under a duplicated path cannot be addressed by docs_read "
                "and cannot be identified in a citation. Usually running page "
                "furniture misread as a heading; see chunk.furniture_headings."
            )
        lines.append(f"- pages_without_heading: {r['pages_without_heading']}")
        lines.append(f"- mean_section_chars: {r['mean_section_chars']:.0f}")
        lines.append(f"- pages: {r['page_count']}")
        lines.append(f"- docling: {r['docling_version']}")
        if r["filename"].lower().startswith("csp_client_manual"):
            lines.append(
                "- acceptance check (§1.2 / §7): re-measure max_depth vs docling "
                "2.92 (was effectively 0). Heading-level inference in ≥2.120.3 "
                "should raise this."
            )
        lines.append("")
        if r["structure_score"] < 0.5:
            flagged.append(r["filename"])

    if flagged:
        lines.append("## Flagged for review")
        for name in flagged:
            lines.append(f"- {name}")
        lines.append("")

    text = "\n".join(lines)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text, encoding="utf-8")
    return text
